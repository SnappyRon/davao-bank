-- 1. Table: fx_rates
create table if not exists public.fx_rates (
  base text not null,
  quote text not null,
  rate_date date not null,
  rate numeric(18, 8) not null check (rate > 0),
  source text not null default 'Frankfurter / European Central Bank',
  fetched_at timestamptz not null default now(),
  primary key (base, quote, rate_date)
);

create index if not exists idx_fx_rates_pair_date
  on public.fx_rates (base, quote, rate_date desc);

-- 2. Row Level Security: Authenticated customers can select; direct client writes forbidden
alter table public.fx_rates enable row level security;

drop policy if exists "fx_rates_select_authenticated" on public.fx_rates;
create policy "fx_rates_select_authenticated"
  on public.fx_rates
  for select
  to authenticated
  using (true);

drop policy if exists "fx_rates_select_anon" on public.fx_rates;
create policy "fx_rates_select_anon"
  on public.fx_rates
  for select
  to anon
  using (true);

-- Ensure anon and authenticated clients cannot insert, update, or delete
revoke insert, update, delete on public.fx_rates from public, anon, authenticated;
grant select on public.fx_rates to anon, authenticated;
grant all on public.fx_rates to service_role;

-- 3. Stored Procedure: upsert_fx_rates
-- Used by Edge Function / sync service to perform idempotent bulk upserts
create or replace function public.upsert_fx_rates(
  p_rates jsonb
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inserted integer := 0;
begin
  insert into public.fx_rates (base, quote, rate_date, rate, source, fetched_at)
  select
    r->>'base',
    r->>'quote',
    (r->>'rate_date')::date,
    (r->>'rate')::numeric,
    coalesce(r->>'source', 'Frankfurter / European Central Bank'),
    now()
  from jsonb_array_elements(p_rates) as r
  on conflict (base, quote, rate_date)
  do update set
    rate = excluded.rate,
    fetched_at = now();

  get diagnostics v_inserted = row_count;
  return v_inserted;
end;
$$;

revoke all on function public.upsert_fx_rates(jsonb) from public, anon, authenticated;
grant execute on function public.upsert_fx_rates(jsonb) to service_role, postgres;

